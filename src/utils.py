def rmse(a, f) -> float:
    a, f = np.asarray(a, float), np.asarray(f, float)
    return float(np.sqrt(np.mean((a - f) ** 2)))


def mae(a, f) -> float:
    a, f = np.asarray(a, float), np.asarray(f, float)
    return float(np.mean(np.abs(a - f)))


def mape(a, f) -> float:
    a, f = np.asarray(a, float), np.asarray(f, float)
    return float(np.mean(np.abs((a - f) / a)) * 100)


def mase(a, f, insample, m: int = 1) -> float:
    """Mean absolute scaled error (Hyndman & Koehler 2006)."""
    insample = np.asarray(insample, float)
    scale = np.mean(np.abs(insample[m:] - insample[:-m]))
    return float(np.mean(np.abs(np.asarray(a, float) - np.asarray(f, float))) / scale)


def theil_u(a, f) -> float:
    a, f = np.asarray(a, float), np.asarray(f, float)
    na, nf = np.diff(a), np.diff(f)
    if na.size == 0:
        return float("nan")
    return float(np.sqrt(np.mean((a - f) ** 2)) / (np.sqrt(np.mean(a**2)) + np.sqrt(np.mean(f**2))))


def _str_keys(obj):
    """Recursively convert non-string dictionary keys (e.g. Period, numpy ints) to str."""
    if isinstance(obj, dict):
        return {str(k): _str_keys(v) for k, v in obj.items()}
    if isinstance(obj, (list, tuple)):
        return [_str_keys(v) for v in obj]
    return obj


def dump_json(name: str, obj) -> Path:
    path = C.RESULTS / name
    payload = _str_keys(obj)
    path.write_text(json.dumps(payload, indent=2, default=_json_default, allow_nan=True),
                    encoding="utf-8")
    print(f"  json   -> {path.relative_to(C.ROOT)}")
    return path


def _json_default(o):
    if isinstance(o, (np.integer,)):
        return int(o)
    if isinstance(o, (np.floating,)):
        return float(o)
    if isinstance(o, (np.bool_,)):
        return bool(o)
    if isinstance(o, (pd.Period, pd.Timestamp)):
        return str(o)
    if isinstance(o, np.ndarray):
        return o.tolist()
    raise TypeError(f"not JSON serialisable: {type(o)}")


def load_json(name: str):
    return json.loads((C.RESULTS / name).read_text())


def bar_ci(ax, estimates: Mapping[str, float], errors: Mapping[str, float], **kw):
    """Horizontal point-and-interval plot used for parameter confidence bands."""
    names = list(estimates)
    y = np.arange(len(names))
    est = np.array([estimates[n] for n in names], float)
    err = np.array([errors[n] for n in names], float)
    ax.errorbar(est, y, xerr=1.96 * err, fmt="o", color=COL["data"],
                ecolor=COL["accent"], capsize=3, **kw)
    ax.axvline(0, color="k", lw=0.8, ls="--")
    ax.set_yticks(y, names)
    ax.invert_yaxis()
