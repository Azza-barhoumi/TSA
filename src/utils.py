# --------------------------------------------------------------------------
# LaTeX writers
# --------------------------------------------------------------------------
_ESCAPE = {
    "\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#",
    "_": r"\_", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}",
    "^": r"\textasciicircum{}",
}


def tex_escape(s) -> str:
    return "".join(_ESCAPE.get(ch, ch) for ch in str(s))


def fmt(x, nd: int = 3, paren_neg: bool = True) -> str:
    """Format a number for LaTeX tables (handles nan/inf and negative signs)."""
    if x is None:
        return "--"
    try:
        xf = float(x)
    except (TypeError, ValueError):
        return tex_escape(x)
    if not np.isfinite(xf):
        return "--"
    if abs(xf) < 0.5 * 10 ** (-nd):
        return f"{0:.{nd}f}"
    s = f"{xf:.{nd}f}"
    if paren_neg and s.startswith("-"):
        return f"${s}$"
    return s


def stars(p) -> str:
    try:
        p = float(p)
    except (TypeError, ValueError):
        return ""
    if not np.isfinite(p):
        return ""
    if p < 0.01:
        return r"$^{***}$"
    if p < 0.05:
        return r"$^{**}$"
    if p < 0.10:
        return r"$^{*}$"
    return ""


def write_table(
    name: str,
    header: Sequence[str],
    rows: Iterable[Sequence[str]],
    caption: str,
    label: str,
    colspec: str | None = None,
    note: str | None = None,
    fontsize: str = r"\small",
    position: str = "htbp",
    sideways: bool = False,
) -> Path:
    """Write a bare LaTeX ``table`` float (\\input-able from the main document)."""
    if colspec is None:
        colspec = "l" + "r" * (len(header) - 1)
    lines = [
        f"% generated by src/ -- do not edit by hand",
        rf"\begin{{table}}[{position}]",
        r"\centering",
        fontsize,
        rf"\caption{{{caption}}}",
        rf"\label{{{label}}}",
        rf"\begin{{tabular}}{{{colspec}}}",
        r"\toprule",
        " & ".join(header) + r" \\",
        r"\midrule",
    ]
    for r in rows:
        if isinstance(r, str):
            lines.append(r)
        else:
            lines.append(" & ".join(str(c) for c in r) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    if note:
        lines.append(rf"\par\vspace{{2pt}}{{\footnotesize {note}}}")
    lines += [r"\end{table}", ""]
    path = C.TABDIR / f"{name}.tex"
    path.write_text("\n".join(lines), encoding="utf-8")
    print(f"  table  -> {path.relative_to(C.ROOT)}")
    return path


